import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { FILES, checkProject, exportText } from './production.mjs';
import { h3AlignmentLine, h3CutTime } from '../modules/novel-storyboard/scripts/novel-storyboard.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const tempRoot = path.join(root, 'output'); fs.mkdirSync(tempRoot, {recursive: true});
const temp = fs.mkdtempSync(path.join(tempRoot, 'production 测试 '));
const line = '钥匙放这里。';
const flow = Array.from({length: 5}, (_, i) => ({action: `男人在桌旁完成第${i + 1}个动作。`}));
flow.push({speaker: 'C01', line, delivery: '平静'});
const script = {source: '测试故事', params: {actionSeconds: 5}, episodes: [{ep: 1, targetSeconds: 30, beatsClaimed: [], hook: '男人为何紧握钥匙', cliff: '他等待回答', hookBeat: [1, 1], scenes: [{sceneId: 'S01', lighting: '夜内', characters: ['C01'], props: [], flow}]}]};
const cuts = flow.map((_, i) => ({beats: [i + 1, i + 1], seconds: 5, size: 'medium', camera: 'Static Shot', characters: ['C01'], props: [], frame: '中景，男人站在桌旁，暖色光照亮面部', shot: '男人在桌旁缓慢抬眼，保持原来的站姿', lens: '50mm，T2.8', cameraPosition: '桌旁平视', composition: '三分法', eyeline: '桌面钥匙', focus: '人物面部', stability: 'stable'}));
const seg = {id: 'E01-01', sceneIndex: 1, blocking: '男人站在桌旁，面向门口', soundscape: '衣料摩擦声', cuts};
seg.h3Prompt = h3AlignmentLine(cuts) + '\n\nintegrated_multimodal_description:\n' + cuts.map((c, i) => `[Shot ${i + 1}] ${i ? `At ${h3CutTime(i * 5)}, ` : ''}Static Shot. The man stands beside the table and looks down.${i === 5 ? ` He says <d>[Chinese] ${line}</d>.` : ''}`).join('\n') + '\n\noverall_soundscape: Quiet room tone.\n\nnon_diegetic_music: N/A';
const storyboard = {source: '测试故事', episodes: [{ep: 1, segments: [seg]}]};
const project = {root: temp, docs: {script, storyboard}};
let n = 0;
const ok = (condition, label) => {assert.ok(condition, label); n++;};
try {
  const result = checkProject(project); ok(result.errors.length === 0, result.errors.join('\n'));
  ok(result.skipped.some(s => s.includes('未提供 outline')), 'Skipped upstream checks are explicit');
  const text = exportText(project); ok(text.includes('25–30秒'), 'Real 30-second end');
  ok(text.includes(line), 'Exact dialogue survives');
  ok(text.includes('无音乐、BGM'), 'Default no BGM');
  ok(storyboard.params === undefined, 'Source data is not changed');
  const bad = structuredClone(project); bad.docs.storyboard.episodes[0].segments[0].cuts[0].seconds = 4;
  ok(checkProject(bad).errors.some(s => s.includes('精确30秒')), 'Reject 29-second group');
  const badRef = structuredClone(project); badRef.docs.storyboard.episodes[0].segments[0].cuts[0].characters = ['C99'];
  ok(checkProject(badRef).errors.length > 0, 'Reject unknown character');
  const missing = structuredClone(project); delete missing.docs.script;
  ok(checkProject(missing).errors.some(s => s.includes('必须提供')), 'Script dependency cannot be skipped');
  const repeat = structuredClone(project); repeat.docs.storyboard.episodes[0].segments[0].cuts[1].beats = [1, 1];
  ok(checkProject(repeat).errors.length > 0, 'Reject duplicate/missing beat claims');
  const long = structuredClone(project); long.docs.script.episodes[0].scenes[0].flow[5].line = '这是无法在五秒内说完的长台词。'.repeat(5);
  ok(checkProject(long).errors.length > 0, 'Reject overlong dialogue');
  const music = structuredClone(project); music.docs.storyboard.episodes[0].segments[0].music = '钢琴伴奏';
  assert.throws(() => exportText(music), /allow-music/); n++;
  ok(exportText(music, {allowMusic: true}).includes('钢琴伴奏'), 'Explicit music preserved');
  for (const [key, doc] of Object.entries(project.docs)) { const file = path.join(temp, FILES[key]); fs.mkdirSync(path.dirname(file), {recursive: true}); fs.writeFileSync(file, JSON.stringify(doc)); }
  const cli = path.join(root, 'rui-skills/scripts/production.mjs');
  const run = (...args) => spawnSync(process.execPath, [cli, ...args], {cwd: root, encoding: 'utf8', windowsHide: true});
  const exported = run('export-text', temp); ok(exported.status === 0 && exported.stdout.includes(line), 'CLI handles Chinese and spaces');
  const reported = run('report', temp, '--out', path.join(temp, 'review report'));
  ok(reported.status === 0, reported.stderr);
  const html = fs.readFileSync(path.join(temp, 'review report/production-report.html'), 'utf8');
  ok(html.includes('pane-storyboard'), 'Unified report contains storyboard');
  const embeddedBoard = JSON.parse(html.match(/id="storyboard--storyboard-data">([\s\S]*?)<\/script>/)[1]);
  ok(embeddedBoard.params.maxSegmentSeconds === 30, 'Report uses the same thirty-second cap as validation');
  ok(fs.readFileSync(path.join(temp, FILES.storyboard), 'utf8') === JSON.stringify(storyboard), 'Report leaves source data unchanged');
  ok(!fs.readdirSync(path.dirname(path.join(temp, FILES.storyboard))).some(x => x.startsWith('.rui-report-')), 'Report removes its temporary board');
  ok(run('run', '../escape', 'help').status !== 0, 'Module selector cannot escape packaged modules');
} finally {
  const resolved = path.resolve(temp);
  assert.ok(resolved.startsWith(path.resolve(tempRoot) + path.sep));
  fs.rmSync(resolved, {recursive: true, force: true});
}
console.log(`PASS ${n} production integration checks`);
